#!/usr/bin/env python3
"""Refresh the vendored ytdl-nightly copy used for Netzkino offline downloads.

    python3 tools/update_ytdl_nightly.py            # newest commit of ytdl-nightly
    python3 tools/update_ytdl_nightly.py --ref <sha> # pin a specific commit

The package is vendored (not pip-installed) so macOS, Synology and QNAP builds
run offline with the same tested version.

Trimmed copy: MediathekAtlas uses ytdl-nightly's core (YoutubeDL, networking,
utils, InfoExtractor, downloaders) plus the Netzkino extractor. The ~1000 other
site extractors are left out: they are never used, would slow down imports on
old NAS hardware, and some contain embedded third-party API keys that GitHub
push protection rejects. Kept are exactly the extractor modules that importing
the core pulls in (computed below), and a minimal lazy extractor index.
Build helper only; not part of the app packages.
"""
import argparse, json, shutil, subprocess, sys, tempfile
from pathlib import Path

REPO = 'https://github.com/boogietown1981/ytdl-nightly.git'
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'vendor' / 'ytdl_nightly'
LAZY = '''# Generated by MediathekAtlas tools/update_ytdl_nightly.py (trimmed vendor copy).
from __future__ import unicode_literals
from .netzkino import NetzkinoIE

_ALL_CLASSES = [NetzkinoIE]
'''
CLOSURE = r'''
import sys
sys.path.insert(0, sys.argv[1])
import youtube_dl, youtube_dl.YoutubeDL, youtube_dl.extractor.common, youtube_dl.extractor.netzkino
import youtube_dl.downloader, youtube_dl.postprocessor
print('\n'.join(sorted(k.rsplit('.', 1)[1] for k in sys.modules if k.startswith('youtube_dl.extractor.'))))
'''


def main(argv=None):
    a = argparse.ArgumentParser(description=__doc__)
    a.add_argument('--ref', default='', help='Commit/Tag; leer = aktueller Standardzweig')
    args = a.parse_args(argv)
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / 'ytdl'
        subprocess.run(['git', 'clone', '--quiet', REPO, str(src)], check=True)
        if args.ref:
            subprocess.run(['git', '-C', str(src), 'checkout', '--quiet', args.ref], check=True)
        commit = subprocess.run(['git', '-C', str(src), 'rev-parse', 'HEAD'], check=True,
                                capture_output=True, text=True).stdout.strip()
        version = {}
        exec((src / 'youtube_dl' / 'version.py').read_text('utf-8'), version)
        staged = Path(tmp) / 'staged'
        shutil.copytree(src / 'youtube_dl', staged / 'youtube_dl',
                        ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
        extractor = staged / 'youtube_dl' / 'extractor'
        (extractor / 'lazy_extractors.py').write_text(LAZY, 'utf-8')
        # Import closure of the core with the minimal index (-I: isolated mode).
        names = subprocess.run([sys.executable, '-I', '-c', CLOSURE, str(staged)], check=True,
                               capture_output=True, text=True).stdout.split()
        keep = {n + '.py' for n in names} | {'__init__.py', 'lazy_extractors.py'}
        for p in extractor.iterdir():
            if p.is_dir():
                shutil.rmtree(p)
            elif p.name not in keep:
                p.unlink()
        for p in staged.rglob('__pycache__'):
            shutil.rmtree(p)
        shutil.copy2(src / 'LICENSE', staged / 'LICENSE')
        (staged / 'VENDOR.json').write_text(json.dumps({
            'name': 'ytdl-nightly', 'repository': REPO[:-4], 'commit': commit,
            'version': version['__version__'], 'license': 'Unlicense (public domain), see LICENSE',
            'trimmed': True, 'extractor_modules': sorted(keep),
            'updated_with': 'tools/update_ytdl_nightly.py'}, indent=2) + '\n')
        # Replace only after the new copy is complete.
        if TARGET.exists():
            shutil.rmtree(TARGET)
        shutil.copytree(staged, TARGET)
    print(f'ytdl-nightly {version["__version__"]} ({commit[:10]}) nach {TARGET} übernommen, '
          f'{len(keep)} Extraktor-Module')


if __name__ == '__main__':
    main()
